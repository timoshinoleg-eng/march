/**
 * Единый источник правды для портфолио и кейсов.
 *
 * Три типа карточек:
 *   1. CLIENT      — реальные клиентские работы (метрики проверены владельцем)
 *   2. OWN_PRODUCT — собственные продукты (RestoBot)
 *   3. RND         — open-source и R&D (1C AI Workbench)
 *
 * Заменяет захардкоженные массивы в:
 *   - components/sections/Cases.tsx
 *   - app/cases/page.tsx
 *
 * ПРАВИЛА:
 *   - CLIENT-кейсы: только реальные метрики (с корректировкой вниз до рыночных).
 *   - OWN_PRODUCT: без «готов», без публичных тарифов, честный статус.
 *   - RND: без клиентских метрик, без «production-ready».
 *
 * Все кейсы сохраняют дисклеймер:
 *   «Название изменено по соглашению о конфиденциальности»
 *   (если менялись название или имя клиента).
 *
 * Метрики откорректированы вниз до реалистичных рыночных значений
 * (по согласованию с владельцем, 2026-07).
 */

import { COMPANY } from './company';

export type PortfolioType = 'client' | 'own-product' | 'rnd';

export type PortfolioStatus = 'production' | 'closed-beta' | 'in-development' | 'pilot';

export interface Metric {
  /** Короткая подпись. */
  label: string;
  /** Значение, например «−45%», «2 мин», «+35%». */
  value: string;
}

export interface PortfolioItem {
  id: string;
  type: PortfolioType;
  /** Заголовок карточки. */
  title: string;
  /** Отрасль или категория (для фильтра). */
  category: string;
  /** Описание в одну-две строки (для карточки-тизера). */
  summary: string;
  /** Подробное описание задачи (для страницы кейса). */
  problem?: string;
  /** Что сделали. */
  solution?: string;
  /** Что вошло во внедрение. */
  implementation?: string;
  /** Срок внедрения. */
  duration?: string;
  /** Метрики результата. Пустой массив для R&D/OWN_PRODUCT. */
  metrics: Metric[];
  /** Цитата клиента. Только для type=client и с дисклеймером. */
  testimonial?: {
    quote: string;
    author: string;
    /** Обязательный дисклеймер, если имя/название изменены. */
    isAnonymized: boolean;
  };
  /** Текущий статус (для own-product и rnd). */
  status?: PortfolioStatus;
  /** Внешняя ссылка (GitHub, demo). */
  link?: {
    url: string;
    label: string;
  };
  /** Дата последнего обновления (ISO, для сортировки/schema). */
  updatedAt?: string;
}

